// Shades of Purple — theme builder.
//
// Single source of truth lives in `src/`:
//   - src/palette.js         → every color, named, defined once
//   - src/themes/*.js        → key → palette-name maps + tokenColors
//   - src/sections.js        → canonical section order for output
//
// `npm run build` regenerates the three `themes/*.json` files from source.
// The colors are whatever the palette says — change a value in one place,
// rebuild, and it propagates everywhere it is referenced.

const fs = require('fs');
const path = require('path');
const { emitColorsBody } = require('./sections');

const OUT = [
	['./themes/dark', 'shades-of-purple-color-theme.json'],
	['./themes/super-dark', 'shades-of-purple-color-theme-super-dark.json'],
	['./themes/light', 'shades-of-purple-color-theme-light.json'],
];

function render(theme) {
	const body = emitColorsBody(theme.colors);
	const tokens = JSON.stringify(theme.tokenColors, null, '\t').replace(/\n/g, '\n\t');
	return (
		'{\n' +
		'\t// Theme Color reference.\n' +
		'\t// https://code.visualstudio.com/docs/getstarted/theme-color-reference\n' +
		'\t// This file is generated by `npm run build` — edit src/ instead.\n' +
		`\t"$schema": ${JSON.stringify(theme.$schema || 'vscode://schemas/color-theme')},\n` +
		`\t"name": ${JSON.stringify(theme.name)},\n` +
		`\t"type": ${JSON.stringify(theme.type)},\n` +
		'\t"colors": {\n' +
		body +
		'\t},\n' +
		`\t"tokenColors": ${tokens}\n` +
		'}\n'
	);
}

let count = 0;
for (const [mod, file] of OUT) {
	const theme = require(mod);
	const text = render(theme);
	fs.writeFileSync(path.join(__dirname, '..', 'themes', file), text);
	console.log(`✓ ${file} — ${Object.keys(theme.colors).length} colors, ${theme.tokenColors.length} token rules`);
	count++;
}
console.log(`Built ${count} themes from src/.`);
